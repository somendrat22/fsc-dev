package com.fsc.supply_chain_common_operations.securities;

import com.fsc.supply_chain_common_operations.utilities.JwtUtility;
import io.jsonwebtoken.Claims;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

import java.io.IOException;

@Component
public class JwtFilter extends OncePerRequestFilter {

    private JwtUtility jwtUtility;

    @Autowired
    public JwtFilter(JwtUtility jwtUtility){
        this.jwtUtility = jwtUtility;
    }

    @Override
    protected void doFilterInternal(HttpServletRequest request,
                                    HttpServletResponse response,
                                    FilterChain filterChain) throws ServletException, IOException {
        // First step in the filter is to get the jwtToken
        String jwtToken = request.getHeader("token");
        // As we are containing nothing inside the token, So we should reject the request.
        if(jwtToken ==  null || jwtToken.isEmpty()){
            // if you are calling doFilter without setting any kind of aunthentication. So, request will get rejected.
            filterChain.doFilter(request, response);
            return;
        }

        jwtToken = jwtToken.trim();

        // We need to validate this token is valid token. That means this token is generated by us.
        // If we are recieving exception so filter will throw exception

        Claims claims = jwtUtility.extractAllClaims(jwtToken);

        // If token is valid then only we are going to arrive at this line and we will create usernamepassword authentication

        UsernamePasswordAuthenticationToken authenticationToken = new UsernamePasswordAuthenticationToken(claims, null, null );
        SecurityContextHolder.getContext().setAuthentication(authenticationToken);

        // If we are calling doFilter after setting up authentication then that means we are approving the request

        filterChain.doFilter(request, response);
    }
}
